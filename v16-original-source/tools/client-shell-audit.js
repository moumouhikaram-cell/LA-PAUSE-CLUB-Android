'use strict';
const fs=require('fs'),assert=require('assert');
const A='app/src/main/assets/';
const index=fs.readFileSync(A+'index.html','utf8');
const shell=fs.readFileSync(A+'client-shell.js','utf8');
const css=fs.readFileSync(A+'client-shell.css','utf8');
const count=(s,x)=>s.split(x).length-1;
assert.strictEqual(count(index,'client-shell.js'),1,'exactly one client-shell.js must be loaded');
for(const dead of ['p1-floor.js','venue-experience.js','master-v2-welcome.js','client-hardening.js','client-persistent-dock.js','client-final.js'])assert(!index.includes(dead),`legacy UI runtime must not load: ${dead}`);
assert(index.includes('master-v2-runtime.js')&&index.includes('master-v2-safety.js'),'transactional business runtime must remain loaded');
assert(shell.includes('window.renderView=route'),'single shell must own renderView');
assert.strictEqual(count(shell,'window.renderView=route'),1,'renderView must be assigned once by client shell');
assert.strictEqual(count(shell,'window.nativeBack=function'),1,'back behavior must have one owner');
for(const x of ['csHome','csStations','csOverview','csBilliards','csSetup'])assert(shell.includes(x),`missing customer route ${x}`);
for(const x of ['BILLIARD_TABLE','SNOOKER_TABLE','PC_GAMING','SIM_RACING','CONSOLE'])assert(shell.includes(x),`missing resource type ${x}`);
for(const bad of ['CDC MASTER','Où sont les 3 420 lignes','System Status','BLOCKED_EXTERNAL','ACTIVE_LOCAL','CommandEnvelope','DomainEvent schema'])assert(!shell.includes(bad),`developer copy leaked to client shell: ${bad}`);
assert(css.includes('safe-area-inset-bottom'),'mobile safe area missing');
assert(css.includes('.cs-dock'),'single dock styling missing');
assert(!shell.includes('PHASE 1 ·'),'phase copy leaked');
console.log('CLIENT_SHELL_AUDIT_OK');
