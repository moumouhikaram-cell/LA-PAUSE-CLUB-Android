'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..');
const core=fs.readFileSync(path.join(root,'app/src/main/assets/v250/saas-core.js'),'utf8');
const integrity=fs.readFileSync(path.join(root,'app/src/main/assets/v250/accounting-integrity-v271.js'),'utf8');
const fail=msg=>{console.error('V271_ACCOUNTING_RUNTIME_FAIL',msg);process.exit(1);};
const ok=(v,msg)=>{if(!v)fail(msg);};
const localStorage={getItem:()=>null,setItem:()=>{},removeItem:()=>{}};
const window={Android:null};window.window=window;
const ctx={window,localStorage,console,Date,Math,JSON,Object,Array,String,Number,Boolean,RegExp,Intl,setTimeout,clearTimeout};
vm.createContext(ctx);
vm.runInContext(core,ctx,{filename:'saas-core.js'});
vm.runInContext(integrity,ctx,{filename:'accounting-integrity-v271.js'});
const A=ctx.window.LPOS,S=A.state,now=Date.now();
S.payments=[];S.refunds=[];
S.payments.push({id:'p1',amount:100,status:'REFUNDED',method:'cash',at:now});
S.refunds.push({id:'r1',paymentId:'p1',amount:100,at:now});
ok(A.grossRevenueToday()===100,'gross must retain the original posted payment');
ok(A.refundsToday()===100,'refund ledger must report the refund once');
ok(A.revenueToday()===0,'full refund must net to zero, never minus the sale twice');
S.payments=[];S.refunds=[];
S.payments.push({id:'p2',amount:100,status:'PAID',method:'card',at:now});
S.refunds.push({id:'r2',paymentId:'p2',amount:20,at:now});
ok(A.grossRevenueToday()===100&&A.refundsToday()===20&&A.revenueToday()===80,'partial refund arithmetic must net exactly once');
S.payments.push({id:'failed',amount:900,status:'FAILED',at:now});
ok(A.grossRevenueToday()===100&&A.revenueToday()===80,'failed payment must not enter revenue');
console.log('V271_GROSS_REFUND_NET_ACCOUNTING_OK');
console.log('V271_NO_DOUBLE_REFUND_SUBTRACTION_OK');